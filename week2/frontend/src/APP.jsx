import { useState, useRef, useEffect } from "react";

import MarkdownResponse from "./MarkdownResponse";
import "./App.css";

const API_URL = "http://127.0.0.1:8000/api/chat";

export default function App() {
  const [message, setMessage] = useState("");
  const [intent, setIntent] = useState("general_question");
  const [messages, setMessages] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const messagesEndRef = useRef(null);

   useEffect(() => {
    messagesEndRef.current?.scrollIntoView({
      behavior: "smooth",
      block: "end",
    });
  }, [messages, loading]);

  async function sendMessage(event) {
    event.preventDefault();

    const text = message.trim();
    if (!text || loading) return;

    setMessages((previous) => [
      ...previous,
      { role: "user", content: text },
    ]);

    setMessage("");
    setError("");
    setLoading(true);

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          message: text,
          intent: intent,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          data.detail || data.error || "The server could not process your request."
        );
      }

      const answer =
        data.response ?? data.answer ?? data.message;

      if (typeof answer !== "string") {
        throw new Error(
          "The API response has no text field. Check the response schema in main.py."
        );
      }

      setMessages((previous) => [
        ...previous,
        { role: "assistant", content: answer },
      ]);
    } catch (err) {
      setError(
        err.message ||
          "Unable to connect to the backend. Check that FastAPI is running."
      );
    } finally {
      setLoading(false);
    }
  }

  function clearChat() {
    setMessages([]);
    setError("");
  }

  return (
    <div className="app-shell">
      <aside className="sidebar">
        <div className="brand">
          <div className="brand-icon">✳</div>
          <div>
            <h2>Neural Chat</h2>
            <p>WEEK 02 · LLM WORKSHOP</p>
          </div>
        </div>

        <button className="new-chat" onClick={clearChat}>
          <span>＋</span> New conversation
        </button>

        <div className="sidebar-label">YOUR WORKSPACE</div>

        <div className="sidebar-item active">
          <span>◈</span> AI Assistant
        </div>

        <div className="sidebar-item">
          <span>⌘</span> Structured Generation
        </div>

        <div className="sidebar-bottom">
          <div className="status-dot" />
          <div>
            <strong>Backend connection</strong>
            <p>FastAPI · Groq LLM</p>
          </div>
        </div>
      </aside>

      <main className="main-panel">
        <header className="topbar">
          <div>
            <span className="topbar-title">AI Assistant</span>
            <span className="model-tag">LLM · Markdown</span>
          </div>
          <div className="topbar-status">
            <span className="status-dot" />
            Local workspace
          </div>
        </header>

        <section className="chat-area">
          {messages.length === 0 ? (
            <div className="welcome">
              <div className="welcome-symbol">✳</div>
              <p className="eyebrow">YOUR AI WORKSPACE</p>
              <h1>What can I help you<br />understand today?</h1>
              <p className="welcome-description">
                Ask a question and get a response generated by your connected
                language model, formatted with Markdown.
              </p>

              <div className="suggestion-grid">
                <button
                  onClick={() =>
                    setMessage("Explain how a large language model works")
                  }
                >
                  <span>◈</span>
                  <strong>Understand LLMs</strong>
                  <small>Learn how language models work</small>
                </button>

                <button
                  onClick={() =>
                    setMessage("Explain Retrieval-Augmented Generation")
                  }
                >
                  <span>⌕</span>
                  <strong>Explore RAG</strong>
                  <small>Understand retrieval and generation</small>
                </button>

                <button
                  onClick={() =>
                    setMessage("Explain Python API integration")
                  }
                >
                  <span>{"{ }"}</span>
                  <strong>Learn API integration</strong>
                  <small>Connect Python with an LLM</small>
                </button>

                <button
                  onClick={() =>
                    setMessage("Explain Markdown with examples")
                  }
                >
                  <span>≡</span>
                  <strong>Format responses</strong>
                  <small>Headings, lists and code blocks</small>
                </button>
              </div>
            </div>
          ) : (
            <div className="messages">
              {messages.map((item, index) => (
                <div
                  className={`message-row ${item.role}`}
                  key={`${index}-${item.role}`}
                >
                  <div className="avatar">
                    {item.role === "user" ? "Y" : "✳"}
                  </div>
                  <div className="message-content">
                    <div className="message-author">
                      {item.role === "user" ? "You" : "AI Assistant"}
                    </div>
                    {item.role === "assistant" ? (
                      <MarkdownResponse content={item.content} />
                    ) : (
                      <p className="user-message">{item.content}</p>
                    )}
                  </div>
                </div>
              ))}

              {loading && (
                <div className="message-row assistant">
                  <div className="avatar">✳</div>
                  <div className="message-content">
                    <div className="message-author">AI Assistant</div>
                    <div className="typing">
                      <span />
                      <span />
                      <span />
                      <small>Generating response...</small>
                    </div>
                  </div>
                </div>
              )}

              <div className="messages-end" ref={messagesEndRef} />

            </div>
          )}
        </section>

        <div className="composer-area">
          {error && (
            <div className="error-message">
              <strong>Request failed:</strong> {error}
            </div>
          )}

          <form className="composer" onSubmit={sendMessage}>
            <textarea
              value={message}
              onChange={(event) => setMessage(event.target.value)}
              onKeyDown={(event) => {
                if (event.key === "Enter" && !event.shiftKey) {
                  event.preventDefault();
                  event.currentTarget.form?.requestSubmit();
                }
              }}
              placeholder="Message your AI assistant..."
              rows={2}
              disabled={loading}
            />

            <div className="composer-footer">
              <div className="composer-options">
                <label htmlFor="intent">Intent</label>
                <select
                  id="intent"
                  value={intent}
                  onChange={(event) => setIntent(event.target.value)}
                  disabled={loading}
                >
                  <option value="general_question">General question</option>
                  <option value="order_tracking">Order tracking</option>
                  <option value="payment_issue">Payment issue</option>
                  <option value="current_time">Current time</option>
                </select>
              </div>

              <button
                className="send-button"
                type="submit"
                disabled={loading || !message.trim()}
                aria-label="Send message"
              >
                {loading ? "..." : "↑"}
              </button>
            </div>
          </form>

          <p className="disclaimer">
            AI-generated responses may be inaccurate. This assistant does not
            access real order or payment records unless you connect those systems.
          </p>
        </div>
      </main>
    </div>
  );
}
